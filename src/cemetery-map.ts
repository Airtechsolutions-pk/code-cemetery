import type { Graveyard } from "./types.js";

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

const TOMBSTONE_SVG = `<svg viewBox="0 0 40 56" width="40" height="56"><path d="M20 2 C10 2 4 10 4 20 L4 52 L36 52 L36 20 C36 10 30 2 20 2 Z" fill="#6b7280" stroke="#374151" stroke-width="2"/><rect x="0" y="52" width="40" height="4" fill="#4b5563"/><text x="20" y="30" text-anchor="middle" font-size="16">🪦</text></svg>`;

export function renderCemeteryMap(yard: Graveyard): string {
  const aiCount = yard.graves.filter((g) => g.likelyAiBorn).length;
  const byKind: Record<string, number> = {};
  for (const g of yard.graves) byKind[g.kind] = (byKind[g.kind] ?? 0) + 1;

  const tombstones = yard.graves
    .map(
      (g, i) => `
      <div class="tomb ${g.likelyAiBorn ? "ai" : ""}" title="${esc(g.filePath)}:${g.line}">
        ${TOMBSTONE_SVG}
        <div class="tname">${esc(g.name)}</div>
        <div class="tkind">${g.kind} · ${g.linesOfCode} LOC</div>
        ${g.likelyAiBorn ? '<div class="ai-badge">🤖 AI-born</div>' : ""}
      </div>`,
    )
    .join("\n");

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>🪦 Code Cemetery</title>
<style>
  :root { color-scheme: dark; }
  body { font-family: ui-monospace, Menlo, monospace; background: #0b1020; color: #cbd5e1; margin: 0; padding: 2rem; }
  h1 { font-size: 1.6rem; color: #e2e8f0; }
  .stats { display: flex; gap: 1rem; flex-wrap: wrap; margin: 1rem 0 2rem; }
  .stat { background: #131a33; border: 1px solid #24304f; border-radius: 10px; padding: .8rem 1.2rem; }
  .stat b { color: #f8fafc; font-size: 1.3rem; display: block; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(150px, 1fr)); gap: 1.2rem; }
  .tomb { background: #131a33; border: 1px solid #24304f; border-radius: 10px; padding: 1rem; text-align: center; position: relative; }
  .tomb.ai { border-color: #7c3aed; box-shadow: 0 0 12px rgba(124,58,237,.25); }
  .tname { margin-top: .5rem; font-weight: bold; color: #f1f5f9; word-break: break-all; }
  .tkind { font-size: .75rem; color: #64748b; }
  .ai-badge { margin-top: .4rem; font-size: .7rem; background: #2e1065; color: #c4b5fd; border-radius: 999px; padding: 2px 8px; display: inline-block; }
  footer { margin-top: 2rem; color: #475569; font-size: .8rem; }
</style>
</head>
<body>
  <h1>🪦 The Code Cemetery</h1>
  <div class="stats">
    <div class="stat"><b>${yard.graves.length}</b>graves</div>
    <div class="stat"><b>${yard.totalLinesOfCode}</b>lines at rest</div>
    <div class="stat"><b>${aiCount}</b>🤖 AI-born</div>
    ${Object.entries(byKind).map(([k, n]) => `<div class="stat"><b>${n}</b>${k}s</div>`).join("")}
  </div>
  <div class="grid">${tombstones}</div>
  <footer>Scanned ${yard.scannedFiles} files at ${yard.scannedAt} · generated by code-cemetery 🪦</footer>
</body>
</html>`;
}
