import { randomInt } from "node:crypto";
import type { Grave } from "./types.js";

const EPITAPHS = [
  "Here lies code that was written with hope and executed with none.",
  "Gone to the great garbage collector, finally.",
  "Never imported, never forgotten. Well — never imported, anyway.",
  "It compiled. That is the kindest thing that can be said.",
  "Believed by its creator. Referenced by no one.",
  "Awaited a caller that never came.",
  "Dead on arrival. Tests optional. Now officially at rest.",
];

const CAUSES = [
  "refactoring",
  "an optimistic abstraction",
  "a requirement that changed over lunch",
  "copy-paste optimism",
  "one TODO too many",
  "a merge conflict survivor with no purpose",
  "AI enthusiasm",
];

function pick<T>(arr: T[]): T {
  return arr[Math.floor(randomInt(arr.length))]!;
}

export function writeObituary(grave: Grave): string {
  const kindLabels: Record<string, string> = {
    file: "a whole file",
    export: "an export",
    function: "a function",
    class: "a class",
    interface: "an interface",
    type: "a type alias",
  };
  const kindLabel = kindLabels[grave.kind] ?? "a symbol";

  const lines: string[] = [];
  lines.push(`🪦  OBITUARY — ${grave.name}`);
  lines.push("");
  lines.push(`    ${kindLabel.charAt(0).toUpperCase() + kindLabel.slice(1)} of ${grave.filePath}:${grave.line},`);
  lines.push(`    ${grave.linesOfCode} lines of sincere intention,`);
  lines.push(`    has passed away, cause of death: ${pick(CAUSES)}.`);
  lines.push("");
  lines.push(`    "${pick(EPITAPHS)}"`);
  lines.push("");
  if (grave.bornAt) {
    lines.push(`    Born: ${grave.bornAt.slice(0, 10)}`);
  }
  if (grave.likelyAiBorn) {
    lines.push("    🤖  Suspected AI-born (speculative code generated but never called):");
    for (const ev of grave.aiEvidence) lines.push(`        - ${ev}`);
  }
  lines.push("");
  lines.push("    Survived by: the 400 other functions that actually get called.");
  return lines.join("\n");
}

export function writeCommitMessage(graves: Grave[]): string {
  const n = graves.length;
  const loc = graves.reduce((a, g) => a + g.linesOfCode, 0);
  const title = `🪦 bury ${n} dead symbol${n === 1 ? "" : "s"} (-${loc} lines)`;
  const body = [
    "",
    "In loving memory of:",
    ...graves.map((g) => `  - ${g.name} (${g.filePath}:${g.line})`),
    "",
    "May they rest in /dev/null.",
    "",
    "Generated by code-cemetery 🪦",
  ].join("\n");
  return `${title}\n${body}`;
}
